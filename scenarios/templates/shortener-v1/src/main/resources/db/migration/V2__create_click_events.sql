-- One row per redirect. clicked_day is the UTC calendar day, computed by the application so
-- per-day statistics do not depend on the database session time zone.
CREATE TABLE click_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id        BIGINT NOT NULL REFERENCES links (id) ON DELETE CASCADE,
    clicked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    clicked_day    DATE NOT NULL,
    -- Host part of the Referer header only (no path or query: those can carry personal data).
    referrer_host  VARCHAR(255)
);

CREATE INDEX ix_click_events_link_day ON click_events (link_id, clicked_day);
CREATE INDEX ix_click_events_clicked_at ON click_events (clicked_at);
