-- Short links. Codes and aliases share one namespace; the unique constraint is what makes
-- alias creation safe under concurrency (insert and handle the conflict, never check-then-insert).
CREATE TABLE links (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)   NOT NULL,
    target_url  VARCHAR(2048) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE,
    -- SHA-256 (hex) of the management token; the token itself is shown once and never stored.
    token_hash  CHAR(64)      NOT NULL,
    CONSTRAINT uk_links_code UNIQUE (code)
);

CREATE INDEX ix_links_expires_at ON links (expires_at);
